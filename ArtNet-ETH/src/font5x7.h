inline char fontUpper(char c) {
  return (c >= 'a' && c <= 'z') ? (char)(c - 'a' + 'A') : c;
}

inline const FontGlyph *fontLookup(char c) {
  c = fontUpper(c);
  for (unsigned i = 0; i < sizeof(FONT5X7) / sizeof(FONT5X7[0]); i++) {
    if (FONT5X7[i].ch == c) return &FONT5X7[i];
  }
  return nullptr;
}
